CREATE TABLE IF NOT EXISTS zu_grant_awards_raw (
  record_key STRING NOT NULL COMMENT 'SHA-256 logical version key derived from the source record identifier and payload hash',
  source_record_id STRING NOT NULL COMMENT 'Stable source identifier; derive from the approved award ID or delivery and row when no award ID exists',
  source_award_id STRING COMMENT 'Institutional or external award identifier supplied by ZU',
  source_delivery_id STRING COMMENT 'Identifier for the approved file, extract, or API delivery',
  source_object_uri STRING COMMENT 'Sanitized source file or object location; must not contain credentials',
  source_row_number BIGINT,
  source_format STRING COMMENT 'For example json, csv, xlsx, or api_json',
  visibility_classification STRING COMMENT 'Approved handling classification supplied with the institutional delivery',
  source_updated_at TIMESTAMP,
  received_at TIMESTAMP NOT NULL,
  record_hash STRING NOT NULL COMMENT 'SHA-256 of the canonical raw record payload',
  raw_record_json STRING NOT NULL COMMENT 'Complete source row serialized as JSON; access must follow the approved visibility classification',
  ingestion_run_id STRING NOT NULL
)
USING DELTA
COMMENT 'Versioned raw historical grant and award records from an approved ZU institutional source';

