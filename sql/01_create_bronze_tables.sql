CREATE TABLE IF NOT EXISTS ingestion_runs (
  ingestion_run_id STRING NOT NULL COMMENT 'UUID generated by the ingestion notebook',
  source_system STRING NOT NULL COMMENT 'Source system, for example zu_scholars',
  dataset_name STRING NOT NULL COMMENT 'Logical source dataset being ingested',
  started_at TIMESTAMP NOT NULL,
  completed_at TIMESTAMP,
  status STRING NOT NULL COMMENT 'started, succeeded, partial, or failed',
  request_parameters_sanitized STRING COMMENT 'JSON request parameters with credentials removed',
  watermark_or_cursor_start STRING,
  watermark_or_cursor_end STRING,
  pages_requested BIGINT NOT NULL,
  records_received BIGINT NOT NULL,
  records_inserted BIGINT NOT NULL,
  records_updated BIGINT NOT NULL,
  records_unchanged BIGINT NOT NULL,
  records_failed BIGINT NOT NULL,
  http_status_summary STRING COMMENT 'JSON map of HTTP status to count',
  error_message STRING,
  created_by STRING COMMENT 'Databricks user that started the run'
)
USING DELTA
COMMENT 'One row per source ingestion execution';

CREATE TABLE IF NOT EXISTS ingestion_errors (
  error_id STRING NOT NULL,
  ingestion_run_id STRING NOT NULL,
  source_system STRING NOT NULL,
  dataset_name STRING NOT NULL,
  source_record_id STRING,
  request_context_sanitized STRING,
  error_type STRING NOT NULL,
  error_message STRING NOT NULL,
  raw_error_payload STRING,
  occurred_at TIMESTAMP NOT NULL
)
USING DELTA
COMMENT 'Record-level and request-level errors captured by Bronze ingestion jobs';

